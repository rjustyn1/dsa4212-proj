"""Generate the sensitivity table for the paired confirmation comparison.

The table contrasts the reported shared-rate confirmation (seeds 301--305) with
the same comparison using the superseded A10G seed-305 SOAP--Muon run and with
the initial comparison at the boundary-selected rate (seeds 201--205).  All
values are computed from the committed per-run metrics.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from analyze_confirmation import analyse_pair, load_metrics, mean, paired_t_interval


SHARED_RATE_SEEDS = (301, 302, 303, 304, 305)
INITIAL_SEEDS = (201, 202, 203, 204, 205)


def paired_rows(
    metrics_dir: Path, seeds: tuple[int, ...], soap_overrides: dict[int, Path] | None = None
) -> list[dict[str, Any]]:
    """Analyse each seed pair, optionally replacing selected SOAP--Muon runs."""
    overrides = soap_overrides or {}
    rows = []
    for seed in seeds:
        soap = (
            json.loads(overrides[seed].read_text())
            if seed in overrides
            else load_metrics(metrics_dir, seed, "soap")
        )
        rows.append(analyse_pair(seed, load_metrics(metrics_dir, seed, "baseline"), soap))
    return rows


def summary_cells(deltas: list[float]) -> tuple[str, str]:
    """Return the mean (with pairs favoring SOAP--Muon) and its paired-t interval."""
    low, high = paired_t_interval(deltas)
    favoring = sum(delta < 0 for delta in deltas)
    return (
        f"${mean(deltas):+.4f}$ ({favoring}/{len(deltas)})",
        f"$[{low:+.4f}, {high:+.4f}]$",
    )


def render_sensitivity_table(
    comparisons: list[tuple[str, list[dict[str, Any]]]], output: Path
) -> None:
    lines = [
        "% Generated by scripts/generate_sensitivity_table.py; do not edit manually.",
        "\\begin{table}[t]",
        "\\caption{How the main result changes under two alternatives. Each entry gives the mean difference (SOAP--Muon minus Moonlight Muon) over five seeds, the number of seeds on which SOAP--Muon is better, and the 95\\% confidence interval. Rows: the main experiment (seeds 301--305); the same with the original A10G run for seed 305; and the earlier comparison at $1.2\\times10^{-3}$ (seeds 201--205).}",
        "\\label{tab:sensitivity}",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{l c c}",
        "\\hline",
        "Comparison & Curve area & Final loss \\\\",
        "\\hline",
    ]
    for label, rows in comparisons:
        area_mean, area_interval = summary_cells([float(row["area_delta"]) for row in rows])
        final_mean, final_interval = summary_cells([float(row["final_delta"]) for row in rows])
        lines.append(f"{label} & {area_mean} & {final_mean} \\\\")
        lines.append(f" & {area_interval} & {final_interval} \\\\")
    lines.extend(["\\hline", "\\end{tabular}", "\\end{table}", ""])
    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-dir", type=Path, default=Path("results"))
    parser.add_argument("--tables-dir", type=Path, default=Path("report/Tables"))
    args = parser.parse_args()
    args.tables_dir.mkdir(parents=True, exist_ok=True)

    shared_dir = args.results_dir / "shared_rate_confirmation_metrics"
    superseded = {305: shared_dir / "superseded" / "seed305-soap-a10g.json"}
    comparisons = [
        ("Main experiment", paired_rows(shared_dir, SHARED_RATE_SEEDS)),
        ("Original seed-305 run", paired_rows(shared_dir, SHARED_RATE_SEEDS, superseded)),
        (
            "Earlier, $1.2\\times10^{-3}$",
            paired_rows(args.results_dir / "confirmation_metrics", INITIAL_SEEDS),
        ),
    ]
    render_sensitivity_table(comparisons, args.tables_dir / "tab_09_sensitivity.tex")


if __name__ == "__main__":
    main()
