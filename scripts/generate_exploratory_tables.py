"""Generate appendix tables from committed screening and pilot metrics."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


SCREEN_LEARNING_RATES = (3e-4, 6e-4, 1.2e-3, 2.4e-3, 4.8e-3, 9.6e-3)
SHARED_RATE_LEARNING_RATES = (1.2e-3, 2.4e-3, 4.8e-3, 9.6e-3)
SCREEN_ROWS = (
    ("muon", "Moonlight Muon"),
    ("up", "SOAP--Muon, up only"),
    ("down", "SOAP--Muon, down only"),
    ("both", "SOAP--Muon, both"),
)
PILOT_ROWS = (
    (
        "adamw-baseline-a10-seed1-200m.json",
        "AdamW",
        "1",
        "Older single-seed setting; contextual only",
    ),
    (
        "reference-muon-a10-seed1-200m.json",
        "Muon, original settings (LR 0.02; AdamW $3\\times10^{-4}$)",
        "1",
        "Older single-seed setting; contextual only",
    ),
    (
        "reference-muon-a10-seed2-200m.json",
        "Muon, original settings (LR 0.02; AdamW $3\\times10^{-4}$)",
        "2",
        "Older single-seed setting; contextual only",
    ),
    (
        "faithful-soap-muon-lr0030-a10-seed1-200m.json",
        "SOAP--Muon, reference code (LR $3\\times10^{-3}$)",
        "1",
        "Older single-seed tuning pilot; not paired confirmation",
    ),
    (
        "faithful-soap-muon-lr0030-a10-seed2-200m.json",
        "SOAP--Muon, reference code (LR $3\\times10^{-3}$)",
        "2",
        "Older single-seed tuning pilot; not paired confirmation",
    ),
    (
        "superseded-muon-scaling-a10-seed1-200m.json",
        "Muon, replaced scaling code",
        "1",
        "Superseded scaling implementation; retained to document the correction",
    ),
)


def load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def selection_area(metric: dict[str, Any]) -> float:
    curve = metric["training"]["curve"]
    if len(curve) < 3:
        raise ValueError("Expected at least three 10M-token screen checkpoints.")
    curve = curve[:3]
    area = sum(
        (right["tokens_processed"] - left["tokens_processed"])
        * (left["mean_nll"] + right["mean_nll"])
        / 2
        for left, right in zip(curve, curve[1:])
    )
    return area / 40_000_000


def render_screening_table(metrics_dir: Path, output: Path) -> None:
    values: dict[tuple[str, float], float] = {}
    for path in metrics_dir.glob("*.json"):
        metric = load(path)
        if "shared_rate_comparator" in metric:
            continue
        optimizer = metric["optimizer"]
        route = str(optimizer.get("route", "muon"))
        learning_rate = float(
            optimizer["learning_rate"]
            if "learning_rate" in optimizer
            else optimizer["hybrid_learning_rate"]
        )
        values[(route, learning_rate)] = selection_area(metric)

    lines = [
        "% Generated by scripts/generate_exploratory_tables.py; do not edit manually.",
        "\\begin{table*}[t]",
        "\\caption{First round of learning-rate tuning (seed 101, 40M-token runs). Each entry is the area under the validation-loss curve between 10M and 30M tokens, divided by 40M; lower is better. For Moonlight Muon, the learning rate applies to all parameters; for SOAP--Muon, it applies only to the MLP matrices that use the SOAP step, with all other parameters at $1.2\\times10^{-3}$. The Moonlight Muon values above $1.2\\times10^{-3}$ were added after the earlier comparison, and Table~\\ref{tab:shared-rate-screen} gives the second round. Dashes mark settings that were not run.}",
        "\\label{tab:screening-record}",
        "\\centering",
        "\\scriptsize",
        "\\begin{tabular}{l r r r r r r}",
        "\\hline",
        "Optimizer & $3\\times10^{-4}$ & $6\\times10^{-4}$ & $1.2\\times10^{-3}$ & $2.4\\times10^{-3}$ & $4.8\\times10^{-3}$ & $9.6\\times10^{-3}$ \\\\",
        "\\hline",
    ]
    for route, label in SCREEN_ROWS:
        entries = []
        for learning_rate in SCREEN_LEARNING_RATES:
            value = values.get((route, learning_rate))
            entries.append("--" if value is None else f"{value:.3f}")
        lines.append(f"{label} & " + " & ".join(entries) + " \\\\")
    lines.extend(["\\hline", "\\end{tabular}", "\\end{table*}", ""])
    output.write_text("\n".join(lines), encoding="utf-8")


def render_shared_rate_table(metrics_dir: Path, output: Path) -> None:
    values: dict[tuple[str, float], float] = {}
    for path in metrics_dir.glob("*.json"):
        metric = load(path)
        optimizer = metric["optimizer"]
        learning_rate = float(
            optimizer["learning_rate"]
            if "learning_rate" in optimizer
            else optimizer["hybrid_learning_rate"]
        )
        is_shared_rate = "shared_rate_comparator" in metric
        if not is_shared_rate and str(optimizer.get("route")) == "both":
            group_rates = (
                float(optimizer["moonlight_muon_learning_rate"]),
                float(optimizer["hybrid_learning_rate"]),
                float(optimizer["adamw_learning_rate"]),
            )
            is_shared_rate = len(set(group_rates)) == 1
        if is_shared_rate and str(optimizer.get("route")) == "both":
            group_rates = (
                float(optimizer["moonlight_muon_learning_rate"]),
                float(optimizer["hybrid_learning_rate"]),
                float(optimizer["adamw_learning_rate"]),
            )
            if len(set(group_rates)) != 1:
                raise ValueError(f"Shared-rate metric {path} has unequal group rates.")
            values[("SOAP--Muon", learning_rate)] = selection_area(metric)
        elif str(optimizer.get("implementation")) == "moonlight_rms_matched":
            values[("Moonlight Muon", learning_rate)] = selection_area(metric)

    lines = [
        "% Generated by scripts/generate_exploratory_tables.py; do not edit manually.",
        "\\begin{table}[t]",
        "\\caption{Second round of learning-rate tuning (seed 101, 40M-token runs). Every parameter of both optimizers uses the column's learning rate, in units of $10^{-3}$, and SOAP--Muon uses the SOAP step on both MLP matrices. Entries are defined as in Table~\\ref{tab:screening-record}; the 1.2 column reuses runs from that table, which already used one rate for all parameters. Lower is better.}",
        "\\label{tab:shared-rate-screen}",
        "\\centering",
        "\\footnotesize",
        "\\begin{tabular}{l r r r r}",
        "\\hline",
        "Optimizer & 1.2 & 2.4 & 4.8 & 9.6 \\\\",
        "\\hline",
    ]
    for method in ("Moonlight Muon", "SOAP--Muon"):
        entries = [
            f"{values[(method, learning_rate)]:.3f}"
            for learning_rate in SHARED_RATE_LEARNING_RATES
        ]
        lines.append(f"{method} & " + " & ".join(entries) + " " + chr(92) * 2)
    lines.extend(["\\hline", "\\end{tabular}", "\\end{table}", ""])
    output.write_text("\n".join(lines), encoding="utf-8")


def render_pilot_table(metrics_dir: Path, output: Path) -> None:
    lines = [
        "% Generated by scripts/generate_exploratory_tables.py; do not edit manually.",
        "\\begin{table}[t]",
        "\\caption{Earlier single-seed 200M-token runs with varied settings. They are not part of the main experiment and do not rank the optimizers. Lower final loss is better.}",
        "\\label{tab:historical-pilots}",
        "\\centering",
        "\\footnotesize",
        "\\begin{tabular}{p{0.52\\columnwidth} c r}",
        "\\hline",
        "Run & Seed & Final loss \\\\",
        "\\hline",
    ]
    for filename, label, seed, status in PILOT_ROWS:
        metric = load(metrics_dir / filename)
        final_nll = float(metric["validation"]["mean_nll"])
        lines.append(f"{label} & {seed} & {final_nll:.3f} \\\\")
    lines.extend(["\\hline", "\\end{tabular}", "\\end{table}", ""])
    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-dir", type=Path, default=Path("results"))
    parser.add_argument("--tables-dir", type=Path, default=Path("report/Tables"))
    args = parser.parse_args()
    args.tables_dir.mkdir(parents=True, exist_ok=True)
    render_screening_table(args.results_dir / "screening_metrics", args.tables_dir / "tab_06_screening.tex")
    render_shared_rate_table(args.results_dir / "screening_metrics", args.tables_dir / "tab_07_shared_rate_screen.tex")
    render_pilot_table(args.results_dir / "exploratory_metrics", args.tables_dir / "tab_08_historical_pilots.tex")


if __name__ == "__main__":
    main()
